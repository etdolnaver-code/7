CREATE TABLE IF NOT EXISTS admins (
  id text PRIMARY KEY, password text NOT NULL, role text NOT NULL CHECK (role = 'ADMIN'), must_change integer NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY, admin_id text NOT NULL REFERENCES admins(id),
  created_at bigint NOT NULL, last_seen bigint NOT NULL, expires_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS visitors (token_hash text PRIMARY KEY, expires_at bigint NOT NULL);
CREATE TABLE IF NOT EXISTS visitor_drafts (visitor_hash text PRIMARY KEY, data text NOT NULL, expires_at bigint NOT NULL);
CREATE TABLE IF NOT EXISTS videos (
  id text PRIMARY KEY, title text NOT NULL, youtube_id text NOT NULL,
  sort_order integer NOT NULL, visible integer NOT NULL, deleted integer NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS view_events (
  id text PRIMARY KEY, visitor_hash text NOT NULL, video_id text NOT NULL REFERENCES videos(id),
  title text NOT NULL, opened_at text NOT NULL, youtube_id text, completed_at text
);
CREATE TABLE IF NOT EXISTS registrations (
  id text PRIMARY KEY, receipt text UNIQUE NOT NULL, request_key text UNIQUE NOT NULL,
  visitor_hash text NOT NULL, payload_hash text NOT NULL, created_at text NOT NULL,
  start_date text NOT NULL, end_date text NOT NULL, data text NOT NULL
);
CREATE INDEX IF NOT EXISTS registration_dates ON registrations(created_at, start_date, end_date);
CREATE TABLE IF NOT EXISTS rate_limits (key text PRIMARY KEY, count integer NOT NULL, reset_at bigint NOT NULL);
CREATE TABLE IF NOT EXISTS audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at text NOT NULL, actor text NOT NULL, action text NOT NULL, target text, details text NOT NULL
);
